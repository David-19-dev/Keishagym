#!/usr/bin/env node
/* Regenerates frontend/src/lib/exercises-data.js from free-exercise-db.
 *
 *   node scripts/build-exercises.mjs [path-to-exercises.json]
 *
 * Without an argument the dataset is downloaded from the upstream repo.
 *
 * Why this dataset: it is released into the public domain (Unlicense), photos included, so
 * KeishaGym can ship it in a store app. The previous dataset's animations are © Gym visual
 * and would have needed a licence. Each exercise here carries two photos — the start and the
 * end of the movement — which the app alternates to show the motion (components/Media.jsx).
 *
 * The upstream taxonomy is not the app's: it names 17 primary muscles and 12 equipment types
 * with no body-part grouping at all. The tables below translate it into the vocabulary the
 * rest of the app already speaks — the body-part chips in the library, the equipment filter,
 * and the muscle aliases the body map resolves (lib/muscles.js). Anything unmapped is a build
 * error rather than a silent "other": a new upstream value must be a decision, not a default.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const UPSTREAM = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json'

// primary muscle → the body part the library groups it under (keys of BY_BODYPART in muscles.js)
const BODYPART = {
  abdominals: 'waist',
  'lower back': 'back', 'middle back': 'back', lats: 'back', traps: 'back',
  chest: 'chest',
  shoulders: 'shoulders',
  biceps: 'upper arms', triceps: 'upper arms',
  forearms: 'lower arms',
  quadriceps: 'upper legs', hamstrings: 'upper legs', glutes: 'upper legs',
  adductors: 'upper legs', abductors: 'upper legs',
  calves: 'lower legs',
  neck: 'neck',
}

// upstream equipment → the label shown on the filter chips (singular, app wording)
const EQUIPMENT = {
  'body only': 'body weight',
  barbell: 'barbell',
  dumbbell: 'dumbbell',
  cable: 'cable',
  machine: 'machine',
  kettlebells: 'kettlebell',
  bands: 'band',
  'medicine ball': 'medicine ball',
  'exercise ball': 'stability ball',
  'e-z curl bar': 'ez barbell',
  'foam roll': 'foam roller',
  other: 'other',
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'frontend', 'src', 'lib', 'exercises-data.js')

let raw
if (process.argv[2]) {
  raw = readFileSync(process.argv[2], 'utf8')
} else {
  console.log('Downloading upstream dataset…')
  const res = await fetch(UPSTREAM)
  if (!res.ok) throw new Error('Download failed: HTTP ' + res.status)
  raw = await res.text()
}

const data = JSON.parse(raw)
const problems = []
const skipped = []

const exercises = data.map(ex => {
  const frames = (ex.images || []).slice(0, 2)
  if (frames.length < 2) { skipped.push(ex.id); return null }

  const primary = (ex.primaryMuscles || [])[0]
  // cardio is a category, not a muscle — the app keys its time+speed logging off bp === 'cardio'
  const bp = ex.category === 'cardio' ? 'cardio' : BODYPART[primary]
  if (!bp) { problems.push(`${ex.id}: unmapped primary muscle "${primary}"`); return null }

  const eqKey = ex.equipment || 'other'
  const eq = EQUIPMENT[eqKey]
  if (!eq) { problems.push(`${ex.id}: unmapped equipment "${eqKey}"`); return null }

  return {
    id: ex.id,
    n: ex.name,
    bp,
    eq,
    tg: primary || '',
    sm: ex.secondaryMuscles || [],
    st: ex.instructions || [],
    lv: ex.level || '',            // beginner | intermediate | expert — shown on the exercise sheet
    fr: frames,                    // [start, end]; the app alternates them (see Media.jsx)
  }
}).filter(Boolean)

if (problems.length) {
  console.error('Unmapped values — add them to the tables in this script:')
  problems.forEach(p => console.error('  ' + p))
  process.exit(1)
}

exercises.sort((a, b) => a.n.localeCompare(b.n, 'en'))

const header = `// generated by scripts/build-exercises.mjs — do not edit
// Source: yuhonas/free-exercise-db (Unlicense / public domain), photos included.
export const EXDB=`
writeFileSync(out, header + JSON.stringify(exercises) + '\n')

const bpCount = {}
exercises.forEach(e => { bpCount[e.bp] = (bpCount[e.bp] || 0) + 1 })
console.log(`Wrote ${out} — ${exercises.length} exercises, ${(JSON.stringify(exercises).length / 1024).toFixed(0)} KB.`)
console.log('Body parts:', Object.entries(bpCount).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(', '))
if (skipped.length) console.log(`Skipped (no photos): ${skipped.join(', ')}`)
