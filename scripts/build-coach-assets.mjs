#!/usr/bin/env node
/* Generates the two files the Coach Edge Function cannot import from the app at runtime.
 *
 *   node scripts/build-coach-assets.mjs           # write
 *   node scripts/build-coach-assets.mjs --check   # fail if stale (CI)
 *
 * · library.json — the exercise catalogue. The function needs it to check that every id a
 *   proposal references actually exists, and to build payloads for reviews that run with
 *   nobody's browser open. Only the fields the Coach reasons over are kept: an id, a name and
 *   the three taxonomy fields it filters on. Instructions and photos stay out; they would
 *   multiply a payload the model has no use for.
 * · prompts.js — the prompt texts. They are authored as Markdown next to the function (easier
 *   to read and diff than string literals) and bundled here, because a deployed function
 *   cannot be relied on to read its own directory at runtime.
 *
 * Both are committed, so a deploy is a copy of the function directory and nothing else.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const fnDir = join(root, 'supabase', 'functions', 'coach')
const src = join(root, 'frontend', 'src', 'lib', 'exercises-data.js')

const { EXDB } = await import(pathToFileURL(src).href)
const index = EXDB.map(e => ({ id: e.id, n: e.n, bp: e.bp, tg: e.tg, eq: e.eq }))
const library = JSON.stringify({ generated_from: 'frontend/src/lib/exercises-data.js', count: index.length, exercises: index }) + '\n'

const promptDir = join(fnDir, 'prompts')
const prompts = {}
for (const f of readdirSync(promptDir).filter(f => f.endsWith('.md')).sort()) {
  prompts[f.replace(/\.md$/, '')] = readFileSync(join(promptDir, f), 'utf8')
}
const promptsJs = '// generated by scripts/build-coach-assets.mjs from ./prompts/*.md — do not edit\n' +
  'export default ' + JSON.stringify(prompts, null, 1) + '\n'

const outputs = [
  [join(fnDir, 'library.json'), library],
  [join(fnDir, 'prompts.js'), promptsJs],
]

if (process.argv.includes('--check')) {
  let stale = false
  for (const [file, want] of outputs) {
    let have = null
    try { have = readFileSync(file, 'utf8') } catch { /* missing counts as stale */ }
    if (have !== want) { console.error(`${file} is out of date`); stale = true }
  }
  if (stale) { console.error('run: node scripts/build-coach-assets.mjs'); process.exit(1) }
  console.log(`Coach assets in sync (${index.length} exercises, ${Object.keys(prompts).length} prompts).`)
} else {
  for (const [file, data] of outputs) writeFileSync(file, data)
  console.log(`Wrote library.json (${index.length} exercises) and prompts.js (${Object.keys(prompts).join(', ')}).`)
}
